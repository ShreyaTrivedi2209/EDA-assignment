"""## Part B – Data Transformations"""

FIRST_NAME = "rahul"       # <-- change to YOUR first name
REG_NO = "23BCE1234"       # <-- change to YOUR registration number

last4 = int("".join(re.findall(r"\d", REG_NO))[-4:])        # last four digits of the Reg. No.
values = [last4, 12, 45, 7, 33, 58, 21, 90, 64, 5]          # first value = last 4 digits + nine integers
globals()[FIRST_NAME] = np.array(values, dtype=float)       # object named after the first name
Fname = globals()[FIRST_NAME]                               # handy alias used below
print(f"Vector '{FIRST_NAME}':", Fname)

"""### 1. Normalization to [-3, +3], [-1, +1] and [0, 1] (Min-Max)
Formula: x' = a + (x - min)(b - a) / (max - min)
"""

def rescale(x, a, b):
    return a + (x - x.min()) * (b - a) / (x.max() - x.min())

norm_3_3 = rescale(Fname, -3, 3)
norm_1_1 = rescale(Fname, -1, 1)
minmax_0_1 = rescale(Fname, 0, 1)

print("[-3, +3]:", np.round(norm_3_3, 4))
print("[-1, +1]:", np.round(norm_1_1, 4))
print("[ 0, 1]:", np.round(minmax_0_1, 4))

"""### 2. Z-score: z = (x - mean) / sd (sample SD, ddof=1, same as R's scale())"""

zscore = (Fname - Fname.mean()) / Fname.std(ddof=1)
print("Z-score:", np.round(zscore, 4))
print("Mean ~", round(zscore.mean(), 6), "| SD =", round(zscore.std(ddof=1), 6))

"""### 3. Decimal Scaling: x' = x / 10^j, where j is the smallest integer such that max(|x'|) < 1"""

j = 0
while np.max(np.abs(Fname)) / (10 ** j) >= 1:
    j += 1
decimal_scaled = Fname / (10 ** j)
print("j =", j, "-> divide by", 10 ** j)
print("Decimal scaling:", np.round(decimal_scaled, 4))

