"""### 5. Select only numerical features (others removed)"""

X = df.select_dtypes(include="number")
print("Features used:", X.columns.tolist(), "| shape:", X.shape)

"""### 6. Standardize the data"""

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)
X_scaled_df = pd.DataFrame(X_scaled, columns=X.columns)
display(X_scaled_df.describe().loc[["mean", "std"]].round(3))

"""### 7. K-Means with 2 centres"""

km2 = KMeans(n_clusters=2, n_init=25, random_state=123)
km2.fit(X_scaled)

"""### 8. Display K-Means results"""

sizes = np.bincount(km2.labels_)
totss = (X_scaled ** 2).sum()            # total sum of squares (data is centred)
tot_withinss = km2.inertia_
betweenss = totss - tot_withinss

print("K-means clustering with 2 clusters of sizes:", sizes.tolist())
print("Iterations         :", km2.n_iter_)
print(f"Within-cluster SS  : {tot_withinss:.2f}")
print(f"Between-cluster SS : {betweenss:.2f}")
print(f"Total SS           : {totss:.2f}")
print(f"(between_SS / total_SS) = {100 * betweenss / totss:.1f} %")
print("\nCluster assignment (first 15):", km2.labels_[:15])

"""### 9. Cluster centres (standardized scale)"""

centers = pd.DataFrame(km2.cluster_centers_, columns=X.columns).round(3)
