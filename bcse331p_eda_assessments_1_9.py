"""### 10. WCSS for K = 1 to 10"""

wcss = []
for k in range(1, 11):
    km = KMeans(n_clusters=k, n_init=25, random_state=123).fit(X_scaled)
    wcss.append(km.inertia_)
wcss_df = pd.DataFrame({"K": range(1, 11), "WCSS": np.round(wcss, 2)})
wcss_df

"""### 11. Elbow plot"""

# automatic elbow = point farthest from the straight line joining first and last WCSS points
k_vals = np.arange(1, 11)
xn = (k_vals - k_vals.min()) / (k_vals.max() - k_vals.min())
yn = (np.array(wcss) - min(wcss)) / (max(wcss) - min(wcss))
dist = np.abs((yn[-1] - yn[0]) * xn - (xn[-1] - xn[0]) * yn + xn[-1] * yn[0] - yn[-1] * xn[0]) / \
       np.hypot(yn[-1] - yn[0], xn[-1] - xn[0])
k_opt = int(k_vals[np.argmax(dist)])

fig, ax = plt.subplots()
ax.plot(k_vals, wcss, "bo-")
ax.axvline(k_opt, color="red", linestyle="--", label=f"Elbow at K = {k_opt}")
ax.set(title="Elbow Method", xlabel="Number of clusters (K)", ylabel="WCSS (total within-cluster SS)",
       xticks=k_vals)
ax.legend()
plt.show()
print("Elbow recommendation: K =", k_opt)

"""### 12. K-Means with the elbow-recommended K"""

km_final = KMeans(n_clusters=k_opt, n_init=25, random_state=123).fit(X_scaled)
df["cluster"] = km_final.labels_

print("Cluster sizes:\n", df["cluster"].value_counts().sort_index())
print("\nCluster centres (original units):")
display(pd.DataFrame(scaler.inverse_transform(km_final.cluster_centers_), columns=X.columns).round(2))

print("Clusters vs actual vote:")
display(pd.crosstab(df["cluster"], df["vote"]))

